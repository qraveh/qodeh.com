"""Self-host STIX Two Text (SIL OFL 1.1): fetch Google Fonts' woff2 subsets and write an @font-face stylesheet.

Keeps the unicode-range split Google ships, so a page downloads a subset only when it uses its characters.
Usage: python tools/fonts/fetch_stix.py   (run from the repo root; writes static/fonts/stix-two-text/ and
assets/css/extended/fonts.css). Re-running replaces both.
"""
import os, re, ssl, urllib.request

FAMILY = "STIX+Two+Text:ital,wght@0,400;0,600;1,400;1,600"
KEEP = {"latin", "latin-ext", "greek", "cyrillic"}
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
OUT_DIR = os.path.join("static", "fonts", "stix-two-text")
CSS_OUT = os.path.join("assets", "css", "extended", "fonts.css")
CTX = ssl.create_default_context()


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60, context=CTX) as r:
        return r.read()


css = get(f"https://fonts.googleapis.com/css2?family={FAMILY}&display=swap").decode("utf-8")
blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css)
os.makedirs(OUT_DIR, exist_ok=True)
out, seen, total = ["/* STIX Two Text, SIL Open Font License 1.1 (stipub/stixfonts), self-hosted subsets from Google Fonts. Generated by tools/fonts/fetch_stix.py. */"], {}, 0
for subset, block in blocks:
    if subset not in KEEP:
        continue
    style = re.search(r"font-style:\s*(\w+)", block).group(1)
    weight = re.search(r"font-weight:\s*([\d ]+)", block).group(1).strip()
    url = re.search(r"src:\s*url\(([^)]+)\)", block).group(1)
    rng = re.search(r"unicode-range:\s*([^;]+);", block).group(1).strip()
    name = f"stix-two-text-{subset}-{style}.woff2"   # the family is variable: one file per subset and style serves 400-600
    if name not in seen:
        data = get(url)
        open(os.path.join(OUT_DIR, name), "wb").write(data)
        seen[name] = len(data); total += len(data)
    out.append("@font-face{font-family:'STIX Two Text';font-style:%s;font-weight:%s;font-display:swap;"
               "src:url(/fonts/stix-two-text/%s) format('woff2');unicode-range:%s}" % (style, weight, name, rng))
open(CSS_OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
for n, s in sorted(seen.items()):
    print(f"{s:7d}  {n}")
print(f"{total} bytes in {len(seen)} files; {len(out) - 1} @font-face rules -> {CSS_OUT}")
